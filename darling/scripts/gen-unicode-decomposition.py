# Writes unicode_decomposition.h for libsystem_kernel's name comparison (name_equivalence.c): every code point's full
# canonical decomposition, and the canonical combining class of every code point whose class is not zero. Hangul
# syllables are left out; name_equivalence.c decomposes them arithmetically. The data comes from Python's unicodedata,
# which is the Unicode Character Database.
#
# Usage: scripts/gen-unicode-decomposition.py > src/libsystem_kernel/emulation/src/linux_premigration/unicode_decomposition.h
import sys
import unicodedata

HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def main():
	decomps = []
	classes = []
	for cp in range(0x110000):
		if 0xD800 <= cp <= 0xDFFF:
			continue
		ch = chr(cp)
		ccc = unicodedata.combining(ch)
		if ccc:
			classes.append((cp, ccc))
		if HANGUL_FIRST <= cp <= HANGUL_LAST:
			continue
		d = unicodedata.decomposition(ch)
		if d and not d.startswith("<"):
			decomps.append((cp, [ord(c) for c in unicodedata.normalize("NFD", ch)]))

	longest = max(len(d) for _, d in decomps)
	out = sys.stdout
	out.write("// Generated by scripts/gen-unicode-decomposition.py; do not edit.\n")
	out.write("// Unicode Character Database %s, through Python's unicodedata module.\n" % unicodedata.unidata_version)
	out.write("// The data is Copyright (C) Unicode, Inc. and is used under the Unicode License v3\n")
	out.write("// (https://www.unicode.org/license.txt), a permissive licence.\n\n")
	out.write("#define UNICODE_DECOMPOSITION_MAX %d\n\n" % longest)

	out.write("// Code points with a canonical decomposition, sorted: the code point, then its offset and length in\n")
	out.write("// unicode_decomposition_pool.\n")
	out.write("static const struct { unsigned int cp; unsigned short offset; unsigned char length; } "
		"unicode_decompositions[%d] = {\n" % len(decomps))
	pool = []
	for cp, d in decomps:
		out.write("\t{ 0x%X, %d, %d },\n" % (cp, len(pool), len(d)))
		pool.extend(d)
	out.write("};\n\n")

	out.write("static const unsigned int unicode_decomposition_pool[%d] = {\n" % len(pool))
	for i in range(0, len(pool), 8):
		out.write("\t" + " ".join("0x%X," % c for c in pool[i:i + 8]) + "\n")
	out.write("};\n\n")

	out.write("// Code points whose canonical combining class is not zero, sorted, each as (code point << 8) | class.\n")
	out.write("static const unsigned int unicode_combining_classes[%d] = {\n" % len(classes))
	for i in range(0, len(classes), 8):
		out.write("\t" + " ".join("0x%X," % ((cp << 8) | c) for cp, c in classes[i:i + 8]) + "\n")
	out.write("};\n")


if __name__ == "__main__":
	main()
